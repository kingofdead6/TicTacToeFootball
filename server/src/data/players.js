const AWARD_CODES = { B: 'award_ballon_dor', W: 'award_world_cup', U: 'award_ucl' }

const slugify = (s) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')

export const players = raw.map(([name, nationality, position, clubs, awards]) => ({
  id: slugify(name),
  name,
  nationality,
  position,
  clubs,
  awards: [...awards].map((c) => AWARD_CODES[c]),
}))
